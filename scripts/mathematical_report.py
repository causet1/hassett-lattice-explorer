#!/usr/bin/env python3
"""Reproduce the nineteen benchmark component dossiers and K3 certificates."""

import argparse
import json
from math import gcd
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from hassett_lattices import intersection_components, k3_certificate
from audit_hnf import HnfAudit
from verify_certificates import congruence, det, pairing, require
from verify_k3_certificates import verify_k3_certificate

SOURCES = {
    'YY': {'url': 'https://arxiv.org/abs/2103.09132v1', 'locations': '5.1, 5.9, 7.5, 7.11, 8.8--8.9'},
    'ABBVA': {'url': 'https://arxiv.org/abs/1205.0237v4', 'locations': 'Theorem A, Theorem 4, Section 1'},
    'A': {'url': 'https://arxiv.org/abs/1910.10182v2', 'locations': '3.1, 3.2, 3.3'},
    'BRS': {'url': 'https://arxiv.org/abs/1504.05863v6', 'locations': '2.9, 3.4, 3.7'},
    'RS': {'url': 'https://arxiv.org/abs/1707.00999v4', 'locations': 'Theorems 2 and 4'},
}
PAIRS = ((8, 14), (8, 26), (12, 20))


def dossier(pair, c):
    g, t = c['gram'], c['tau']
    index = c['index']
    if pair == (8, 14):
        u = [[1, 0, 1], [0, 1, 0], [0, 0, 1]]
        published_t, reference = t+1, 'ABBVA, Theorem 4'
        target = [[3, 1, 4], [1, 3, t+1], [4, t+1, 10]]
    elif pair == (8, 26):
        u = [[1, 0, 2], [0, 1, 0], [0, 0, 1]]
        published_t, reference = t+2, 'A, Proposition 3.2'
        target = [[3, 1, 7], [1, 3, t+2], [7, t+2, 25]]
    elif index == 1:
        u = [[1, 0, 0], [0, 1, 0], [0, 0, 1]]
        published_t, reference = t, 'YY, Theorem 7.11, M_tau'
        target = [[3, 1, 0], [1, 7, t], [0, t, 4]]
    else:
        u = [[1, 0, 0], [0, -1, 1], [0, 1, 0]]
        published_t, reference = None, 'YY, Theorem 7.11, N_0'
        target = [[3, 1, 1], [1, 3, -3], [1, -3, 7]]
    require(abs(det(u)) == 1 and congruence(g, u) == target, 'Published basis mismatch')
    cert = k3_certificate(g)
    verify_k3_certificate(g, cert)
    w = cert['witness']
    rational_label = (pair[1] if pair[0] == 8 else
                      w['discriminant'] if w and w['discriminant'] in (14, 26) else None)
    rationality = {'status': 'proved_rational' if rational_label else 'not_decided_here',
                  'via_label': rational_label,
                  'scope': 'every smooth cubic in this component' if rational_label else
                           'No irrationality assertion; higher-rank specializations may acquire other labels.',
                  'reference': ('RS, Theorem 2; BRS, 2.9 and 3.4' if rational_label == 14 else
                                'RS, Theorem 4' if rational_label == 26 else None)}
    quadric = None
    if pair[0] == 8:
        q = [1, -1, 0]
        pairings = [pairing(g, q, [int(i == j) for i in range(3)]) for j in range(3)]
        divisor = gcd(gcd(pairings[0], pairings[1]), pairings[2])
        require(divisor in (1, 2), 'Unexpected quadric divisibility')
        # Q.h=2; an odd pairing gives an explicit class pairing to one.
        section = [(t//2), 0, 1] if divisor == 1 else None
        if section:
            require(pairing(g, q, section) == 1, 'Wrong section-class witness')
        quadric = {'plane': [0, 1, 0], 'quadric': q, 'pairings': pairings,
                   'divisibility': divisor, 'section_class': section,
                   'clifford_class': 'trivial' if divisor == 1 else 'nontrivial',
                   'hypotheses': 'Chosen plane is good (smooth discriminant sextic), and A(X) is the displayed rank-three lattice.',
                   'specialization': 'An existing section class persists; nontriviality need not persist after algebraic rank increases.',
                   'reference': 'ABBVA, Theorem A and Section 1' if pair[1] == 14 else 'A, Theorems 3.1 and 3.3'}
    return {'id': c['id'], 'gram': g, 'determinant': c['determinant'],
            'tau': t, 'index': index, 'origins': c['origins'],
            'published': {'basis_columns': u, 'gram': target, 'tau': published_t,
                          'reference': reference}, 'k3_certificate': cert,
            'quadric_fibration': quadric, 'rationality': rationality}


def build_report():
    audit = HnfAudit(50_000_000)
    results = []
    for pair in PAIRS:
        r = intersection_components(*pair)
        checked = audit.result(r)
        results.append({'pair': list(pair), 'normalized_pair': [r['d1'], r['d2']],
                        'classification_audit': checked,
                        'components': [dossier(pair, c) for c in r['components']]})
    return {'schema_version': '1.0', 'sources': SOURCES, 'pairs': results,
            'scope': 'Nineteen benchmark components. Geometry is deduced from the stated published theorems; computations check arithmetic certificates.'}


def markdown(report):
    lines = ['# Certified benchmark components', '',
             'Generated by `python scripts/mathematical_report.py`. Verify without modifying files with `--check`.', '',
             'All matrices use column coordinates and first vector o = h². The accompanying '
             '[JSON](benchmark-components.json) records every Gram, integral basis change, inclusion, '
             'K3 witness/obstruction, and theorem-specific rationality statement. See '
             '[the mathematical audit](math-audit.md) for the proofs and scope.', '',
             'The reported K3 vector is (0,y,z). Its label is primitive because gcd(y,z)=1. '
             '“Rational via d” invokes a geometric theorem for C_d, beyond the K3 arithmetic test. '
             '“Not decided” is not an irrationality claim.', '',
             'For the plane examples, “section” means an integral class pairing to one with '
             'Q=o−P. The Clifford interpretation assumes a good plane and the displayed full '
             'algebraic lattice; it is not assigned to arbitrary higher-rank specializations.', '']
    for r in report['pairs']:
        d1, d2 = r['pair']
        lines += [f'## C{d1} ∩ C{d2}', '',
                  '| t | Published parameter | det | Index | K3 label and vector / obstruction | Quadric section | Rationality |',
                  '|---:|:---|---:|---:|:---|:---|:---|']
        for c in r['components']:
            w = c['k3_certificate']['witness']
            k3 = f"{w['discriminant']}; {w['vector']}" if w else '; '.join(c['k3_certificate']['association']['obstructions'])
            q = c['quadric_fibration']
            section = ('yes' if q['divisibility'] == 1 else 'no, if A(X)=M') if q else 'not applied'
            rational = f"Rational via {c['rationality']['via_label']}" if c['rationality']['via_label'] else 'Not decided'
            p = c['published']['tau'] if c['published']['tau'] is not None else 'N₀'
            lines.append(f"| {c['tau']} | {p} | {c['determinant']} | {c['index']} | {k3} | {section} | {rational} |")
        lines += ['']
    lines += ['## Basis conventions and geometry', '',
              'For C8 ∩ C14 the published basis is (o,P,o+u₂), so the published parameter is t+1. '
              'The degree-four class has square ten; it is not being asserted to be a smooth quintic del Pezzo surface.', '',
              'For C8 ∩ C26 use (o,P,2o+u₂), with parameter t+2. Thus the even-parameter '
              'criterion in Awada agrees with even t in these normalized coordinates.', '',
              'For C12 ∩ C20 the engine orders the labels (20,12). The index-two representative '
              'is converted to Yang–Yu’s N₀ by columns (o,w−u₁,u₁). Its determinant is 20, '
              'whereas the originating lattice has determinant 80. Both markings remain primitive.', '',
              'Every smooth member of the first two intersections is rational by RS Theorems 2 and 4. '
              'For C12 ∩ C20, v=u₁−u₂ supplies labels 26 and 14 at t=1 and t=3, respectively. '
              'The other four lattices have a content-four obstruction to an untwisted K3 marking; '
              'this report makes no irrationality assertion about them.', '',
              'In particular, determinant 32 in C8 ∩ C14 has nontrivial Clifford invariant under '
              'the stated hypotheses while its cubics are rational. BRS supplies the later rationality '
              'argument without assuming the pfaffian locus is open.', '', '## Primary references', '']
    lines += [f"- [{key}]({value['url']}): {value['locations']}." for key, value in SOURCES.items()]
    return '\n'.join(lines)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=Path, default=ROOT/'docs')
    args = parser.parse_args()
    report = build_report()
    files = {'benchmark-components.json': json.dumps(report, indent=2)+'\n',
             'benchmark-components.md': markdown(report)}
    args.output.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        path = args.output/name
        if args.check:
            require(path.read_text() == data, f'Stale mathematical report: {path}')
        else:
            path.write_text(data)
    print('Certified 19 benchmark components, published bases, K3 decisions and geometric annotations.')


if __name__ == '__main__':
    main()
